function item = empty_item()
item = struct('id', '', 'category', '', 'name', '', 'description', '', ...
    'basis', '', 'displayUnit', '', 'internalUnit', '', ...
    'path', {{}}, 'subscript', [], 'valueType', '', 'displayScale', 1, ...
    'displayOffset', 0, 'minimum', -Inf, 'maximum', Inf, ...
    'minimumInclusive', true, 'maximumInclusive', true, ...
    'integerRequired', false, 'writePolicy', '', 'dependencyGroup', '');
end

function catalog = add(catalog, id, category, name, description, basis, ...
    displayUnit, internalUnit, path, subscript, valueType, displayScale, ...
    displayOffset, minimum, maximum, minimumInclusive, maximumInclusive, ...
    integerRequired, writePolicy, dependencyGroup)
item = empty_item();
item.id = id;
item.category = category;
item.name = name;
item.description = description;
item.basis = basis;
item.displayUnit = displayUnit;
item.internalUnit = internalUnit;
item.path = path;
item.subscript = subscript;
item.valueType = valueType;
item.displayScale = displayScale;
item.displayOffset = displayOffset;
item.minimum = minimum;
item.maximum = maximum;
item.minimumInclusive = minimumInclusive;
item.maximumInclusive = maximumInclusive;
item.integerRequired = integerRequired;
item.writePolicy = writePolicy;
item.dependencyGroup = dependencyGroup;
catalog(end+1,1) = item;
end

