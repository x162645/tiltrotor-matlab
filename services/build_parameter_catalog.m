function catalog = add_ki(catalog, id, name, subscript)
catalog = add(catalog, id, '整机质量与惯量', inertia_rate_name(name), ...
    ['当前惯量变化近似中，惯量矩阵随短舱倾转角变化的对角分量 ' name '。'], ...
    '质量与惯量设定', 'kg m^2/rad', 'kg m^2/rad', ...
    {'mass','KI'}, subscript, 'scalar', 1, 0, -Inf, Inf, true, true, ...
    false, 'diagKI', 'inertia');
end

function name = inertia_name(symbol)
switch symbol
    case 'Ixx'
        name = '滚转惯量 Ixx';
    case 'Iyy'
        name = '俯仰惯量 Iyy';
    case 'Izz'
        name = '偏航惯量 Izz';
    case 'Ixy'
        name = '滚转-俯仰耦合惯量 Ixy';
    case 'Ixz'
        name = '滚转-偏航耦合惯量 Ixz';
    case 'Iyz'
        name = '俯仰-偏航耦合惯量 Iyz';
    otherwise
        name = symbol;
end
end

function name = inertia_rate_name(symbol)
switch symbol
    case 'KIxx'
        name = '滚转惯量随倾转角变化系数';
    case 'KIyy'
        name = '俯仰惯量随倾转角变化系数';
    case 'KIzz'
        name = '偏航惯量随倾转角变化系数';
    otherwise
        name = ['惯量变化系数 ' symbol];
end
end

