function unit = internal_unit_for_state(index)
if index <= 3
    unit = 'm/s';
elseif index <= 6
    unit = 'rad/s';
else
    unit = 'rad';
end
end

function catalog = add_rows(catalog, category, rows)
for i = 1:size(rows,1)
    subscript = rows{i,8};
    if isempty(subscript)
        subscript = [];
    end
    catalog = add(catalog, rows{i,1}, category, rows{i,2}, rows{i,3}, ...
        rows{i,4}, rows{i,5}, rows{i,6}, rows{i,7}, subscript, ...
        'scalar', rows{i,9}, rows{i,10}, rows{i,11}, rows{i,12}, ...
        rows{i,13}, rows{i,14}, rows{i,15}, rows{i,16}, rows{i,17});
end
end

function catalog = normalize_catalog_categories(catalog)
for k = 1:numel(catalog)
    id = catalog(k).id;
    if starts_with(id, 'mass.')
        catalog(k).category = '整机质量与惯量';
    end
    if any(strcmp(id, {'mass.mNac','mass.RH_mass','rotor.pivotX', ...
            'rotor.pivotY','rotor.pivotZ','rotor.RH_hub'}))
        catalog(k).category = '倾转机构';
    elseif starts_with(id, 'rotor.')
        if any(strcmp(id, {'rotor.R','rotor.Nb','rotor.chord', ...
                'rotor.rootCut','rotor.twistTip','rotor.bladeMass', ...
                'rotor.Jpolar'}))
            catalog(k).category = '旋翼几何';
        elseif strcmp(id, 'rotor.Omega')
            catalog(k).category = '旋翼运行';
        elseif contains(id, 'induced') || contains(id, 'flap') || ...
                any(strcmp(id, {'rotor.nRadial','rotor.nAzimuth'}))
            catalog(k).category = '旋翼入流与挥舞';
        else
            catalog(k).category = '旋翼气动';
        end
    elseif starts_with(id, 'control.')
        catalog(k).category = '操纵系统';
    end
end
end

function tf = starts_with(text, prefix)
tf = strncmp(text, prefix, numel(prefix));
end
