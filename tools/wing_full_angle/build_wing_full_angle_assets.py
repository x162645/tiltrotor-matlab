def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest().upper()

def pdf_info(path):
    info = {"page_count": "UNKNOWN", "text_extractable": "UNKNOWN", "pdf_header_valid": False}
    try:
        with open(path, "rb") as f:
            info["pdf_header_valid"] = f.read(5) == b"%PDF-"
    except FileNotFoundError:
        return info
    try:
        from pypdf import PdfReader
        reader = PdfReader(str(path))
        info["page_count"] = len(reader.pages)
        sample = ""
        for page in reader.pages[: min(3, len(reader.pages))]:
            try:
                sample += page.extract_text() or ""
            except Exception:
                pass
        info["text_extractable"] = bool(sample.strip())
    except Exception as exc:
        info["text_extractable"] = f"ERROR: {exc}"
    return info

