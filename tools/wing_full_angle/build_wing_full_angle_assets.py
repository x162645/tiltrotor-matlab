# NACA-like surrogate coordinate generator: not an exact 6-series pressure distribution.
def naca4_like(m=0.02, p=0.4, t=0.23, n=161):
    beta = [math.pi * i / (n - 1) for i in range(n)]
    x = [(1 - math.cos(b)) / 2 for b in beta]
    yt = [5*t*(0.2969*math.sqrt(max(xi,0)) - 0.1260*xi - 0.3516*xi**2 + 0.2843*xi**3 - 0.1015*xi**4) for xi in x]
    yc=[]; dyc=[]
    for xi in x:
        if xi < p:
            yc_i = m/(p*p)*(2*p*xi - xi*xi)
            dy_i = 2*m/(p*p)*(p - xi)
        else:
            yc_i = m/((1-p)*(1-p))*((1 - 2*p) + 2*p*xi - xi*xi)
            dy_i = 2*m/((1-p)*(1-p))*(p - xi)
        yc.append(yc_i); dyc.append(dy_i)
    theta = [math.atan(v) for v in dyc]
    upper=[]; lower=[]
    for xi,yti,yci,th in zip(x,yt,yc,theta):
        upper.append((xi - yti*math.sin(th), yci + yti*math.cos(th)))
        lower.append((xi + yti*math.sin(th), yci - yti*math.cos(th)))
    coords = list(reversed(upper)) + lower[1:]
    return coords, upper, lower
