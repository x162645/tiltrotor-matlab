function [CL, CD, meta] = xv15_c81_section_lookup(alphaRad, Mach, rOverR)
%XV15_C81_SECTION_LOOKUP Diagnostic lookup of public XV-15 C81 section data.
%
% This function is intentionally a VALIDATION-DIAGNOSTIC helper, not a
% production airfoil model. It restores the four spanwise C81 regions and
% Mach dependence published in NASA/TP-2004-212262, Appendix A, while OARF
% Run 15 remains external comparison data.
%
% Published span boundaries used here:
%   region 1: root cutout <= r/R < 0.55 (published boundary starts at 0.20;
%             the first section is extended inboard for this diagnostic)
%   region 2: 0.55 <= r/R < 0.80
%   region 3: 0.80 <= r/R < 0.95
%   region 4: 0.95 <= r/R <= 1.00
%
% The lookup covers alpha=-10:...:30 deg, which contains the full incidence
% range reached by the present XV-15 hover diagnostic. Queries outside the
% published diagnostic window are clamped and reported in META.
%
% SOURCE:
% NASA/TP-2004-212262, Appendix A, printed pp. 28-35,
% "XV-15 ROTOR AIRFOILS ... (C81 TABLES; INTERPOLATED SPANWISE)".
%
% CLAIM BOUNDARY:
% NASA reference-model C81 inputs; not raw OARF data and not claimed as
% independent raw airfoil-wind-tunnel truth.

persistent T
if isempty(T)
    T = build_tables();
end

alphaDeg = alphaRad*180/pi;
targetSize = size(alphaDeg);
Mach = Mach + zeros(targetSize);
rOverR = rOverR + zeros(targetSize);

CL = NaN(targetSize);
CD = NaN(targetSize);
region = zeros(targetSize);

region(rOverR < 0.55) = 1;
region(rOverR >= 0.55 & rOverR < 0.80) = 2;
region(rOverR >= 0.80 & rOverR < 0.95) = 3;
region(rOverR >= 0.95) = 4;

alphaUsed = min(max(alphaDeg, T.alphaDeg(1)), T.alphaDeg(end));
alphaClampMask = alphaUsed ~= alphaDeg;
machClampMask = false(targetSize);

for j = 1:4
    mask = region == j;
    if ~any(mask(:))
        continue;
    end

    aq = alphaUsed(mask);

    mCl = T.region(j).machCL;
    mqCl = min(max(Mach(mask), mCl(1)), mCl(end));
    clLocal = interp2(mCl, T.alphaDeg, T.region(j).CL, ...
        mqCl, aq, 'linear');

    mCd = T.region(j).machCD;
    mqCd = min(max(Mach(mask), mCd(1)), mCd(end));
    cdLocal = interp2(mCd, T.alphaDeg, T.region(j).CD, ...
        mqCd, aq, 'linear');

    CL(mask) = clLocal;
    CD(mask) = cdLocal;
    machClampMask(mask) = (mqCl ~= Mach(mask)) | (mqCd ~= Mach(mask));
end

if any(region(:) == 0) || any(~isfinite(CL(:))) || any(~isfinite(CD(:)))
    error('xv15_c81_section_lookup:InvalidLookup', ...
        'C81 lookup produced an uncovered or nonfinite section state.');
end

meta = struct();
meta.sourceClass = 'NASA_TP_2004_212262_C81_REFERENCE_TABLE';
meta.claimBoundary = ...
    'C81_REFERENCE_TABLE_LOOKUP_NO_OARF_FIT_NO_RAW_POLAR_TRUTH_CLAIM';
meta.region = region;
meta.alphaDeg = alphaDeg;
meta.alphaUsedDeg = alphaUsed;
meta.alphaClampCount = nnz(alphaClampMask);
meta.machClampCount = nnz(machClampMask);
meta.alphaRangeDeg = [T.alphaDeg(1), T.alphaDeg(end)];
end

