function S = build_xv15_metal_torsion_reference()
%BUILD_XV15_METAL_TORSION_REFERENCE Source-constrained XV-15 torsion inputs.
%
% This builder transcribes the public CAMRAD II reference-model structural
% inputs published in NASA/TP-2004-212262, Appendix A.  These values are
% REFERENCE-MODEL INPUTS, not claimed to be direct measurements from the
% 1985 OARF Run 14/15 records.
%
% Source locations:
% - Appendix A printed p. 23: RPROP, XQC, KPL.
% - Appendix A printed p. 25: GJ distribution.
% - Main text printed p. 13: baseline pitch stiffness seen by blade =
%   22,400 ft-lb/rad.
%
% Unit contract:
% - GJ is CAMRAD-family torsional stiffness in lbf*ft^2 and is converted to
%   N*m^2.
% - KPL is ft*lbf/rad and is converted to N*m/rad.
% - XQC is nondimensionalized by rotor radius and is positive aft of the
%   elastic axis according to the report nomenclature.

S = struct();
S.source = 'NASA_TP_2004_212262_APPENDIX_A_REFERENCE_CAMRADII_MODEL';
S.sourceClass = 'NASA_REFERENCE_MODEL_INPUT';
S.claimBoundary = [ ...
    'XV15_STEEL_BLADE_CAMRADII_REFERENCE_INPUT_' ...
    'NOT_OARF_RECORD_LEVEL_MEASUREMENT_NO_OARF_FIT'];

S.R_m = 3.81;
S.rR = (0:0.02:1).';

S.XQC_over_R = [ ...
    -0.01303;-0.01268;-0.01233;-0.01199;-0.01164;-0.01129; ...
    -0.01095;-0.01060;-0.01026;-0.00991;-0.00956;-0.00922; ...
    -0.00887;-0.00852;-0.00815;-0.00778;-0.00742;-0.00705; ...
    -0.00671;-0.00638;-0.00605;-0.00572;-0.00539;-0.00506; ...
    -0.00471;-0.00436;-0.00402;-0.00367;-0.00332;-0.00297; ...
    -0.00262;-0.00227;-0.00193;-0.00160;-0.00127;-0.00092; ...
    -0.00055;-0.00019; 0.00017; 0.00052; 0.00088; 0.00122; ...
     0.00157; 0.00191; 0.00225; 0.00260; 0.00300; 0.00335; ...
     0.00368; 0.00402; 0.00435];
S.XQC_m = S.XQC_over_R*S.R_m;

S.GJ_lbf_ft2 = [ ...
    410000;410000;357000;287000;256000;344000;432000;403000; ...
    335000;271000;220000;170000;142200;122400;104900;93700; ...
    82600;74800;68000;62000;58500;55000;51900;48800;45700; ...
    42600;39500;36800;34200;31700;29500;27200;24800;22300; ...
    20200;19000;17900;16500;15000;13570;12290;11010;9940; ...
    8940;7980;7100;6230;5500;4820;4310;4310];

lbf_to_N = 4.4482216152605;
ft_to_m = 0.3048;
ftlbf_to_Nm = 1.3558179483314;
S.GJ_Nm2 = S.GJ_lbf_ft2*lbf_to_N*ft_to_m^2;
S.KPL_ftlbf_per_rad = 22400;
S.KPL_Nm_per_rad = S.KPL_ftlbf_per_rad*ftlbf_to_Nm;

if numel(S.rR) ~= 51 || numel(S.XQC_over_R) ~= 51 || ...
        numel(S.GJ_lbf_ft2) ~= 51
    error('build_xv15_metal_torsion_reference:InvalidSourceVectorLength', ...
        'RPROP, XQC and GJ must each contain 51 source stations.');
end
if any(~isfinite(S.GJ_Nm2)) || any(S.GJ_Nm2 <= 0) || ...
        ~(isfinite(S.KPL_Nm_per_rad) && S.KPL_Nm_per_rad > 0)
    error('build_xv15_metal_torsion_reference:InvalidStiffness', ...
        'Reference stiffness inputs must be finite and positive.');
end

S.referenceNotes = { ...
    'XQC_POSITIVE_AFT_OF_ELASTIC_AXIS'; ...
    'GJ_CAMRAD_FAMILY_TORSIONAL_STIFFNESS_LBF_FT2'; ...
    'KPL_BASELINE_PITCH_STIFFNESS_SEEN_BY_BLADE'; ...
    'REFERENCE_CAMRADII_MODEL_HAS_ONE_TORSION_MODE_AND_FLEXIBLE_PITCH_LINKS'; ...
    'REFERENCE_MODEL_LIMITATIONS_PRECLUDE_OARF_RECORD_LEVEL_TRUTH_CLAIM'};
end
