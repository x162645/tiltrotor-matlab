function [CM, meta] = xv15_c81_moment_lookup(alphaRad, Mach, rOverR)
%XV15_C81_MOMENT_LOOKUP Public XV-15 C81 pitching-moment lookup.
%
% The current CL/CD helper predates M1 stage 2 and intentionally did not
% expose the third C81 table.  This separate helper keeps existing callers
% unchanged while adding the published section pitching-moment coefficient
% needed for source-constrained loaded-torsion diagnostics.
%
% SOURCE:
% NASA/TP-2004-212262, Appendix A, C81 tables CLCD3015--CLCD3018.
% Region boundaries follow xv15_c81_section_lookup.m.
%
% CLAIM BOUNDARY:
% NASA CAMRAD II reference-model C81 input; not raw OARF airfoil truth and
% not fitted to OARF CT/CP/FM.

persistent T
if isempty(T)
    T = build_tables();
end

alphaDeg = alphaRad*180/pi;
targetSize = size(alphaDeg);
Mach = Mach + zeros(targetSize);
rOverR = rOverR + zeros(targetSize);

CM = NaN(targetSize);
region = zeros(targetSize);
region(rOverR < 0.55) = 1;
region(rOverR >= 0.55 & rOverR < 0.80) = 2;
region(rOverR >= 0.80 & rOverR < 0.95) = 3;
region(rOverR >= 0.95) = 4;

alphaUsed = min(max(alphaDeg,T.alphaDeg(1)),T.alphaDeg(end));
alphaClampMask = alphaUsed ~= alphaDeg;
machClampMask = false(targetSize);

for j = 1:4
    mask = region == j;
    if ~any(mask(:)), continue; end
    m = T.region(j).machCM;
    mq = min(max(Mach(mask),m(1)),m(end));
    CM(mask) = interp2(m,T.alphaDeg,T.region(j).CM,mq,alphaUsed(mask),'linear');
    machClampMask(mask) = mq ~= Mach(mask);
end

if any(region(:) == 0) || any(~isfinite(CM(:)))
    error('xv15_c81_moment_lookup:InvalidLookup', ...
        'C81 pitching-moment lookup produced an uncovered/nonfinite state.');
end

meta = struct();
meta.sourceClass = 'NASA_TP_2004_212262_C81_REFERENCE_TABLE';
meta.claimBoundary = 'C81_CM_REFERENCE_LOOKUP_NO_OARF_FIT';
meta.region = region;
meta.alphaDeg = alphaDeg;
meta.alphaUsedDeg = alphaUsed;
meta.alphaClampCount = nnz(alphaClampMask);
meta.machClampCount = nnz(machClampMask);
meta.alphaRangeDeg = [T.alphaDeg(1),T.alphaDeg(end)];
end

