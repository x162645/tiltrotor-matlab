function S = build_xv15_m1d_structural_reference()
%BUILD_XV15_M1D_STRUCTURAL_REFERENCE Public-reference structural inputs.
%
% Source: NASA/TP-2004-212262 Appendix A CAMRAD II XV-15 baseline rotor.
% These values are NASA reference-model inputs, not OARF Run 14/15 matched
% structural measurements. They are used only for analysis-only M1-D
% quasi-static loaded-pitch diagnostics.
%
% Appendix-A native units are the English engineering units of the CAMRAD
% input listing. RPROP is nondimensional radius. GJ is converted here from
% lbf-ft^2 to N-m^2. KPL is converted from ft-lbf/rad to N-m/rad.

S = struct();
S.sourceClass = 'NASA_REFERENCE_MODEL_INPUT';
S.source = 'NASA/TP-2004-212262 Appendix A CAMRAD II XV-15 rotor listing';
S.claimBoundary = ['REFERENCE_MODEL_STRUCTURE_NOT_MATCHED_OARF_RUN14_RUN15_' ...
    'NO_OARF_TARGET_FIT'];

S.rOverR = (0:0.02:1).';

% GJ = 2*410000,357000,...,2*4310 in Appendix A.
S.GJ_lbf_ft2 = [ ...
 410000;410000;357000;287000;256000;344000;432000;403000;335000; ...
 271000;220000;170000;142200;122400;104900;93700;82600;74800;68000; ...
 62000;58500;55000;51900;48800;45700;42600;39500;36800;34200;31700; ...
 29500;27200;24800;22300;20200;19000;17900;16500;15000;13570;12290; ...
 11010;9940;8940;7980;7100;6230;5500;4820;4310;4310];

% XQC is quarter-chord location relative to elastic axis, positive aft.
S.XQC = [ ...
 -0.01303;-0.01268;-0.01233;-0.01199;-0.01164;-0.01129;-0.01095; ...
 -0.01060;-0.01026;-0.00991;-0.00956;-0.00922;-0.00887;-0.00852; ...
 -0.00815;-0.00778;-0.00742;-0.00705;-0.00671;-0.00638;-0.00605; ...
 -0.00572;-0.00539;-0.00506;-0.00471;-0.00436;-0.00402;-0.00367; ...
 -0.00332;-0.00297;-0.00262;-0.00227;-0.00193;-0.00160;-0.00127; ...
 -0.00092;-0.00055;-0.00019;0.00017;0.00052;0.00088;0.00122;0.00157; ...
 0.00191;0.00225;0.00260;0.00300;0.00335;0.00368;0.00402;0.00435];

% Appendix-A TWISTA, retained as a transparent reference geometry vector.
S.twist_deg = [ ...
 34.43;33.49;32.45;31.55;30.79;30.03;29.03;28.03;26.88;25.58; ...
 24.28;23.03;21.78;20.43;18.98;17.53;16.48;15.43;14.20;12.79; ...
 11.38;10.64;9.90;9.03;8.03;7.03;6.43;5.83;5.19;4.51;3.83;3.31; ...
 2.79;2.30;1.84;1.38;0.83;0.27;-0.27;-0.82;-1.37;-1.86;-2.35; ...
 -2.82;-3.27;-3.72;-4.14;-4.56;-4.98;-5.40;-5.82];

lbf_to_N = 4.4482216152605;
ft_to_m = 0.3048;
S.GJ_Nm2 = S.GJ_lbf_ft2*lbf_to_N*ft_to_m^2;
S.Kpl_ftlbf_per_rad = 22400;
S.Kpl_Nm_per_rad = S.Kpl_ftlbf_per_rad*lbf_to_N*ft_to_m;
S.pitchLinkOffsetR = 0.11; % EPH in Appendix A; retained as metadata only.

assert(numel(S.rOverR)==51 && numel(S.GJ_Nm2)==51 && ...
    numel(S.XQC)==51 && numel(S.twist_deg)==51, ...
    'M1-D structural source vectors must contain 51 stations.');
end
